#include <iostream>
#include <vector>
/*
Вам необходимо построить поле для игры «Сапёр» по его конфигурации — высоте, ширине и координатам расставленных на нем мин.
Вкратце напомним правила построения поля для игры «Сапёр»:
поле состоит из клеток с минами и пустых клеток;
клетки с миной обозначаются символом *;
пустые клетки содержат число от 0 до 8 — количество мин на соседних клетках.
Формат ввода
В первой строке содержатся три числа:
число
m от 1 до 100 — количество строк на поле;
число
n от 1 до 100 — количество столбцов на поле;
число
k от 0 до mn
mn — количество мин на поле.
В следующих k строках содержатся пары чисел с координатами мин (номерами строки и столбца). Нумерация ведётся с единицы.
Формат вывода
Выведите построенное поле, разделяя строки поля символом \n, а столбцы — пробелом.
Пример
Ввод
3 2 2
1 1
2 2
Вывод
* 2
2 *
1 1
 */

int main()
{
  // Ввод данных
  size_t m, n, k;
  if (!(std::cin >> m >> n >> k))
  {
    return 1;
  }
  std::vector<std::vector<unsigned char>> field(m, std::vector<unsigned char>(n, '0'));
  for (size_t i = 0; i != k; ++i)
  {
    size_t x, y;
    std::cin >> x >> y;
    field[x - 1][y - 1] = '*';
  }
  // вычисляем соседние с минами клетки
  const int dx[8] = {-1, -1, -1, 0, 0, 1, 1, 1};
  const int dy[8] = {-1, 0, 1, -1, 1, -1, 0, 1};
  for (size_t i = 0; i != m; ++i)
  {
    for (size_t j = 0; j != n; ++j)
    {
      if (field[i][j] == '*')
      {
        continue;
      }
      int cnt = 0;
      for (int dir = 0; dir != 8; ++dir)
      {
        int nx = static_cast<int>(i) + dx[dir];
        int ny = static_cast<int>(j) + dy[dir];
        if (nx >= 0 && nx < static_cast<int>(m) && ny >= 0 && ny < static_cast<int>(n))
        {
          if (field[nx][ny] == '*')
          {
            ++cnt;
          }
        }
      }
      field[i][j] = field[i][j] + cnt;
    }
  }

  // вывод на экран
  std::cout << std::endl;
  for (size_t i = 0; i != m; ++i)
  {
    for (size_t j = 0; j != n; ++j)
    {
      if (j != 0)
      {
        std::cout << " ";
      }
      std::cout << field[i][j];
    }
    std::cout << std::endl;
  }
  return 0;
}